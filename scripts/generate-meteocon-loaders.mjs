import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createJiti } from "jiti";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, "..");
const outputFile = path.join(repoRoot, "src/generated/meteoconLoaders.ts");
const jiti = createJiti(import.meta.url, {
  moduleCache: false,
  fsCache: false,
});

const { WEATHER_CODE_MAP } = await jiti.import(
  path.join(repoRoot, "src/weatherCodes.ts")
);

const fallbackSlugs = ["cloudy", "overcast"];
const iconSlugs = new Set(fallbackSlugs);

for (const descriptor of Object.values(WEATHER_CODE_MAP)) {
  for (const entry of [descriptor.day, descriptor.night]) {
    const slug = entry?.iconSlug?.trim().toLowerCase();

    if (!slug || slug === "not-available") {
      continue;
    }

    iconSlugs.add(slug);
  }
}

const sortedSlugs = [...iconSlugs].sort();
const globSegment = sortedSlugs.join(",");
const quotedSlugLines = sortedSlugs.map(slug => `  "${slug}",`).join("\n");

const fileContents = `/* This file is auto-generated by scripts/generate-meteocon-loaders.mjs. */

export type MeteoconIconLoader = () => Promise<string>;
export type MeteoconLoaderMap = Record<string, MeteoconIconLoader>;

export const SUPPORTED_METEOCON_SLUGS = [
${quotedSlugLines}
] as const;

export const SUPPORTED_METEOCON_SLUGS_SET = new Set<string>(SUPPORTED_METEOCON_SLUGS);

export const animatedColoredLoaders = import.meta.glob(
  "../../node_modules/@meteocons/svg/fill/{${globSegment}}.svg",
  { import: "default" }
) as MeteoconLoaderMap;

export const animatedThemedLoaders = import.meta.glob(
  "../../node_modules/@meteocons/svg/monochrome/{${globSegment}}.svg",
  { import: "default", query: "?raw" }
) as MeteoconLoaderMap;

export const staticColoredLoaders = import.meta.glob(
  "../../node_modules/@meteocons/svg-static/fill/{${globSegment}}.svg",
  { import: "default" }
) as MeteoconLoaderMap;

export const staticThemedLoaders = import.meta.glob(
  "../../node_modules/@meteocons/svg-static/monochrome/{${globSegment}}.svg",
  { import: "default", query: "?raw" }
) as MeteoconLoaderMap;
`;

await mkdir(path.dirname(outputFile), { recursive: true });
await writeFile(outputFile, fileContents);
